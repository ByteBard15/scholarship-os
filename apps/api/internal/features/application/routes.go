package application

import "github.com/go-chi/chi/v5"

func MountRoutes(r chi.Router, h *Handler) {
	r.Get("/applications", h.List)
	r.Post("/applications", h.Create)
	r.Get("/applications/{applicationID}", h.Get)
	r.Patch("/applications/{applicationID}", h.Update)
	r.Delete("/applications/{applicationID}", h.Delete)
	r.Get("/applications/{applicationID}/summary", h.Summary)
	r.Get("/applications/{applicationID}/readiness", h.Readiness)
	r.Get("/applications/{applicationID}/eligibility", h.Eligibility)
	r.Get("/applications/{applicationID}/requirements", h.ListRequirements)
	r.Post("/applications/{applicationID}/requirements", h.CreateRequirement)
	r.Get("/applications/{applicationID}/requirements/{requirementID}", h.GetRequirement)
	r.Patch("/applications/{applicationID}/requirements/{requirementID}", h.UpdateRequirement)
	r.Delete("/applications/{applicationID}/requirements/{requirementID}", h.DeleteRequirement)
	r.Get("/applications/{applicationID}/requirements/{requirementID}/evidence", h.ListEvidence)
	r.Post("/applications/{applicationID}/requirements/{requirementID}/evidence", h.CreateEvidence)
	r.Get("/applications/{applicationID}/requirements/{requirementID}/evidence-suggestions", h.EvidenceSuggestions)
	r.Get("/applications/{applicationID}/deadlines", h.ListDeadlines)
	r.Post("/applications/{applicationID}/deadlines", h.CreateDeadline)
	r.Patch("/applications/{applicationID}/deadlines/{deadlineID}", h.UpdateDeadline)
	r.Delete("/applications/{applicationID}/deadlines/{deadlineID}", h.DeleteDeadline)
	r.Get("/applications/{applicationID}/funding", h.ListFunding)
	r.Post("/applications/{applicationID}/funding", h.CreateFunding)
	r.Patch("/applications/{applicationID}/funding/{fundingID}", h.UpdateFunding)
	r.Delete("/applications/{applicationID}/funding/{fundingID}", h.DeleteFunding)
	r.Get("/applications/{applicationID}/contacts", h.ListContacts)
	r.Post("/applications/{applicationID}/contacts", h.CreateContact)
	r.Patch("/applications/{applicationID}/contacts/{contactID}", h.UpdateContact)
	r.Delete("/applications/{applicationID}/contacts/{contactID}", h.DeleteContact)
	r.Get("/applications/{applicationID}/supervisors", h.ListSupervisors)
	r.Post("/applications/{applicationID}/supervisors", h.CreateSupervisor)
	r.Patch("/applications/{applicationID}/supervisors/{supervisorID}", h.UpdateSupervisor)
	r.Delete("/applications/{applicationID}/supervisors/{supervisorID}", h.DeleteSupervisor)
	r.Get("/applications/{applicationID}/urls", h.ListURLs)
	r.Post("/applications/{applicationID}/urls", h.CreateURL)
	r.Delete("/applications/{applicationID}/urls/{urlID}", h.DeleteURL)
	r.Get("/applications/{applicationID}/tasks", h.ListTasks)
	r.Post("/applications/{applicationID}/tasks", h.CreateTask)
	r.Patch("/applications/{applicationID}/tasks/{taskID}", h.UpdateTask)
	r.Delete("/applications/{applicationID}/tasks/{taskID}", h.DeleteTask)
	r.Post("/applications/{applicationID}/tasks/{taskID}/complete", h.CompleteTask)
	r.Post("/applications/{applicationID}/tasks/{taskID}/reopen", h.ReopenTask)
	r.Post("/applications/{applicationID}/research", h.RunResearch)
	r.Get("/applications/{applicationID}/research", h.ListResearch)
	r.Post("/applications/{applicationID}/research/mark-stale", h.MarkResearchStale)
	r.Get("/applications/{applicationID}/research/{runID}", h.GetResearch)
	r.Get("/applications/{applicationID}/research/{runID}/sources", h.ListSources)
	r.Get("/applications/{applicationID}/research/{runID}/findings", h.ListFindings)
	r.Patch("/applications/{applicationID}/research/{runID}/findings/{findingID}", h.ReviewFinding)
	r.Post("/applications/{applicationID}/research/{runID}/apply", h.ApplyResearch)
	r.Get("/deadlines/upcoming", h.Upcoming)
	r.Get("/dashboard", h.Dashboard)
}
